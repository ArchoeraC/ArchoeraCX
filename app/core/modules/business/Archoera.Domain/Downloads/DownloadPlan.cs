namespace Archoera.Domain.Downloads;

/// <summary>
/// Compatibility-only entry in <c>post[]</c>. The v1 executor never runs post
/// actions (natives/overrides are handled by the C# continuation), and Rust
/// accepts arbitrary JSON values there, so the producer keeps each entry as
/// opaque JSON text and round-trips it verbatim.
/// </summary>
/// <param name="Json">A complete JSON value, normally an object.</param>
public sealed record DownloadPostAction(string Json);

/// <summary>
/// The complete download plan: the only input to <c>archoera_dl</c>.
/// Serialized in camelCase by
/// <c>Archoera.Application.Downloads.DownloadPlanJson</c>.
/// </summary>
public sealed record DownloadPlan
{
    /// <summary>Wire schema version; only <c>1</c> is accepted.</summary>
    public int SchemaVersion { get; init; } = DownloadPlanLimits.SchemaVersion;

    /// <summary>Idempotency key generated by <see cref="DownloadPlanBuilder"/>.</summary>
    public string PlanId { get; init; } = string.Empty;

    /// <summary>Absolute download root. The executor canonicalizes it.</summary>
    public string Root { get; init; } = string.Empty;

    /// <summary>Desired parallel streams, 1..64.</summary>
    public int Concurrency { get; init; } = DownloadPlanLimits.DefaultConcurrency;

    /// <summary>Plan priority used for cross-plan scheduling.</summary>
    public int Priority { get; init; }

    /// <summary>Bytes per second cap; <c>0</c> means unlimited.</summary>
    public long BandwidthLimit { get; init; }

    /// <summary>Sum of <c>files[].size</c>. Informational; Rust recomputes it.</summary>
    public long TotalBytes { get; init; }

    /// <summary>Executor tuning options.</summary>
    public DownloadPlanOptions Options { get; init; } = DownloadPlanOptions.Default;

    /// <summary>Files to download.</summary>
    public IReadOnlyList<PlanFile> Files { get; init; } = [];

    /// <summary>Compatibility field; empty for every plan this client produces.</summary>
    public IReadOnlyList<DownloadPostAction> Post { get; init; } = [];
}
