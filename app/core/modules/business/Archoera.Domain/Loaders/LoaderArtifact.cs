namespace Archoera.Domain.Loaders;

/// <summary>How an artifact comes into existence.</summary>
public enum LoaderArtifactKind
{
    /// <summary>A processor output, for example the patched client jar.</summary>
    Generated,

    /// <summary>A file copied out of the installer zip.</summary>
    Extracted,
}

/// <summary>Base directory an artifact path is relative to.</summary>
public enum LoaderArtifactLocation
{
    /// <summary>Relative to the instance root (version JSON and root-scoped data).</summary>
    Root,

    /// <summary>Relative to the shared libraries root declared by the manifest.</summary>
    Libraries,
}

/// <summary>
/// One file that must exist after loader installation.
/// </summary>
/// <param name="Key">
/// Logical producer key: a data variable name such as <c>PATCHED</c>, or
/// <c>installer:&lt;zip entry&gt;</c> for extracted files.
/// </param>
/// <param name="RelativePath">
/// Forward-slash path relative to <see cref="Location"/>. Never absolute.
/// </param>
/// <param name="Sha1">Expected lower-case hex SHA-1, or <see langword="null"/> when unknown.</param>
/// <param name="Size">Expected size in bytes when the installer declares it.</param>
/// <param name="ProducerIndex">
/// Zero-based index into <see cref="LoaderArtifactManifest.Processors"/>, or
/// <c>-1</c> for extracted/embedded files and launch libraries with no known producer.
/// </param>
/// <param name="RequiredForLaunch">
/// True when the artifact is required by the merged version JSON at launch
/// (notably libraries whose <c>downloads.artifact.url</c> is empty).
/// </param>
/// <param name="Kind">Generated by a processor, or extracted from the installer.</param>
/// <param name="Location">Base directory for <paramref name="RelativePath"/>.</param>
public sealed record LoaderArtifact(
    string Key,
    string RelativePath,
    string? Sha1,
    long? Size,
    int ProducerIndex,
    bool RequiredForLaunch,
    LoaderArtifactKind Kind,
    LoaderArtifactLocation Location = LoaderArtifactLocation.Libraries)
{
    /// <summary>True when a hash comparison is possible.</summary>
    public bool HasSha1 => !string.IsNullOrWhiteSpace(Sha1);
}
